    <section>
        <h2>Youniverse has two main goals:</h2>
        <ul>
            <li>Reduce the allostatic load of plural systems and their loved ones</li>
            <li>Promote healthy internal and external communication</li>
        </ul>
        <p>Every decision made for the project is decided based on how well it accomplishes one or both of our core goals.</p>
    </section>
    <section>
        <h2> Reducing Allostatic Load</h2>
        <h3>What is Allostatic load?</h3>
        <p>To put it simply, it is the increased likelihood of developing physical and mental illnesses due to chronic stress.</p>
        <cite>Allostatic Load: Importance, Markers, and Score Determination in Minority and Disparity Populations by Erik J Rodriquez, Edward N Kim, Anne E Sumner, Anna M Nápoles, Eliseo Pérez-Stable</cite>
        <h3>Steps the project has taken to accomplish this goal:</h3>
        <ul>
            <li>Framework built with plurals and their loved ones in mind</li>
            <li>Easy navigation of site and switching features</li>
            <li>Streamlined onboarding allowing users to start messaging as soon as possible</li>
            <li>No involuntary minority labels</li>
            <li>No one will be distinguished as plural or singlet. All profiles will look the same, regardless of the individual's situation. Any identity labels used will be up to individual users to distinguish themselves and will not be imposed by the website.</li>
        </ul>
    </section>
    <section>
        <h2>Promote healthy and safe internal and external communication</h2>
        <h3>Steps taken to assist in improved communication:</h3>
        <ul>
            <li>Private messaging across all profiles for one on one conversations</li>
            <li>System group chats</li>
            <li>Feed for system updates and news (on the roadmap!)</li>
            <li>Personalized notifications for each profile to minimize spam from other headmates' profiles</li>
            <li>Connecting to profiles on different accounts requires the unique ID for the specific profile trying to be reached</li>
            <li>Using local-first programming principles whenever possible</li>
        </ul>
    </section>
